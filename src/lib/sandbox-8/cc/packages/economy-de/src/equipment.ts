/** BGL A+V: k = 100/v + 6.5·n/(2v) %/month of the new price (n years of use, v months on hand). */
function bglOwning(price: number, n: number, v: number): Param {
  const k = 100 / v + (6.5 * n) / (2 * v);
  return p(Math.round((price * k) / 100), 'EUR/mo', BGL_DERIVED, low(`A+V k = 100/${v} + 6.5·${n}/(2·${v}) = ${k.toFixed(2)} %/month × ${price} EUR (estimated new price)`));
}
function bglRepair(price: number, pctPerMonth: number): Param {
  return p(Math.round((price * pctPerMonth) / 100), 'EUR/mo', BGL_REPAIR, low(`repair ${pctPerMonth} %/month of new price (ESTIMATE, BGL earthmoving typ. 1.5–2.5 %)`));
}
/** Values copied from research tables.bgl_style_monthly_cost_estimates. */
const tableOwning = (v: number, row: string) => p(v, 'EUR/mo', cite(BGL_DERIVED, row), low());
const tableRepair = (v: number, row: string) => p(v, 'EUR/mo', cite(BGL_DERIVED, row), low());

const purchase = (v: number, note?: string) => p(v, 'EUR', PURCHASE_EST, low(note));
const rental = (v: number, range: [number, number], src = BAU_RENTAL, confidence: 'high' | 'medium' | 'low' = 'medium', note?: string) =>
  p(v, 'EUR/d', src, note ? { range, confidence, note } : { range, confidence });
const fuel = (v: number, range: [number, number], note: string) => p(v, 'l/h', cite(CAT_PHB, note), { range, confidence: 'medium' });
const tank = (v: number) => p(v, 'l', ASSUMPTION, low('typical datasheet tank size of the class, not in research'));
const service500 = p(500, 'h', CAT_SERVICE, { confidence: 'medium', note: 'engine oil + fuel filters every 500 h' });
const serviceH = (v: number) => p(v, 'h', ASSUMPTION, { range: [4, 10], ...low('500-h service incl. travel of the fitter') });
const mtbf = (v: number) => p(v, 'h', ASSUMPTION, { range: [Math.round(v * 0.5), Math.round(v * 2)], ...low('assumption: no German fleet failure statistic (Cat uses 95 % mechanical availability)') });
const mttr = (v: number) =>
  p(v, 'h', ASSUMPTION, {
    range: [Math.max(0.5, v * 0.25), v * 4],
    ...low('mean hands-on repair time of the fitter on site (hose, sensor … pump); call-out travel and parts waits are simulated separately'),
  });
const travel = (v: number, src = CAT_PHB, range?: [number, number]) => p(v, 'km/h', src, range ? { range, confidence: 'medium' } : { confidence: 'medium' });

/** Truck hire with driver (Naumann) → bare hire: rate × 8 h − driver (LG3 × 1.91) − fuel. */
const truckRental = (v: number, ratePerHour: number) =>
  p(v, 'EUR/d', cite(NAUMANN, `${ratePerHour} EUR/h with driver`), {
    range: [Math.round(v * 0.8), Math.round(v * 1.3)],
    confidence: 'low',
    note: `derived bare hire: ${ratePerHour} × 8 h − driver ≈ 366 EUR/d (23.97 EUR/h × 1.91) − fuel ≈ 140 EUR/d`,
  });

