// @ts-nocheck — plain JS, run by node only
// The repo's code entries (code/, the source of truth until avenDB carries them, C4) as two generated modules, each
// entry named by the BLAKE3 hash of what it holds (game/code/files.js says how files make entries):
//   code/index.js     views/ and logic/: what the pages and the API run (the pages bundle it)
//   code/decided.js   configs/ and mips/: Sandbox 7's configs, version by version, and every MIP as it landed (only the
//                     API reads it: game/code/decided.js)
// Run it after changing anything in code/; src/lib/code/code.test.js fails while either is behind.
//
//   node scripts/code-index.mjs            write both
//   node scripts/code-index.mjs --check    exit 1 if either is not what the files make
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { blake3 } from '@noble/hashes/blake3.js';
import { bytesToHex, utf8ToBytes } from '@noble/hashes/utils.js';
import { entriesOfFiles } from '../game/code/files.js';

const ROOT = fileURLToPath(new URL('../code/', import.meta.url));
const MODULES = { 'index.js': ['views', 'logic'], 'decided.js': ['configs', 'mips'] };
const NAMES = { 'index.js': 'ENTRIES', 'decided.js': 'DECIDED' };

/** every file under code/'s entry folders: { 'views/x/view.html': text } */
export function filesOf(root = ROOT) {
	const out = {};
	const walk = (dir) => {
		for (const n of readdirSync(`${root}${dir}`).sort()) {
			const p = `${dir}${n}`;
			if (statSync(`${root}${p}`).isDirectory()) walk(`${p}/`);
			else if (dir) out[p] = readFileSync(`${root}${p}`, 'utf8');
		}
	};
	walk('');
	return out;
}

const hashOf = (text) => bytesToHex(blake3(utf8ToBytes(text)));

/** every entry, or only those under the top folders `tops` */
export function entries(root = ROOT, tops = MODULES['index.js']) {
	const all = entriesOfFiles(filesOf(root), hashOf);
	return Object.fromEntries(Object.entries(all).filter(([ref]) => tops.includes(ref.split('/')[0])));
}

export const indexText = (all, name = 'ENTRIES') => `// GENERATED by scripts/code-index.mjs from the files beside it. Do not edit: change the files, then run
// \`node scripts/code-index.mjs\`. Each entry: its ref (its path here), its entry.json, its files, and their BLAKE3 hash.
export const ${name} = ${JSON.stringify(all, null, '\t')};
`;

/** each generated module's text: { 'index.js': text, 'decided.js': text } */
export const moduleTexts = (root = ROOT) => Object.fromEntries(Object.entries(MODULES).map(([file, tops]) => [file, indexText(entries(root, tops), NAMES[file])]));

if (import.meta.url === `file://${process.argv[1]}`) {
	const texts = moduleTexts();
	if (process.argv.includes('--check')) {
		for (const [file, text] of Object.entries(texts)) {
			let now = '';
			try {
				now = readFileSync(`${ROOT}${file}`, 'utf8');
			} catch {}
			if (now !== text) {
				console.error(`code/${file} is behind code/: run node scripts/code-index.mjs`);
				process.exit(1);
			}
		}
		console.log('code/index.js and code/decided.js are current');
	} else {
		for (const [file, text] of Object.entries(texts)) writeFileSync(`${ROOT}${file}`, text);
		console.log(`code/index.js: ${Object.keys(entries()).length} entries; code/decided.js: ${Object.keys(entries(ROOT, MODULES['decided.js'])).length}`);
	}
}
