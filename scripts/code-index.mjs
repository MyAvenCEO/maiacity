// @ts-nocheck — plain JS, run by node only
// The repo's code entries (code/, the source of truth until avenDB carries them, C4) as one module both the pages and
// the API import: code/index.js, generated from the files beside it, each entry named by the BLAKE3 hash of what it
// holds. Run it after changing anything in code/; src/lib/code/code.test.js fails while code/index.js is behind.
//
//   node scripts/code-index.mjs            write code/index.js
//   node scripts/code-index.mjs --check    exit 1 if code/index.js is not what the files make
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { blake3 } from '@noble/hashes/blake3.js';
import { bytesToHex, utf8ToBytes } from '@noble/hashes/utils.js';

const ROOT = fileURLToPath(new URL('../code/', import.meta.url));

/** JSON with its keys in order, so the same entry always hashes the same */
const canonical = (v) => (Array.isArray(v) ? `[${v.map(canonical).join(',')}]` : v && typeof v === 'object' ? `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${canonical(v[k])}`).join(',')}}` : JSON.stringify(v));

export function entries(root = ROOT) {
	const out = {};
	const walk = (dir) => {
		const names = readdirSync(`${root}${dir}`).sort();
		if (names.includes('entry.json')) {
			const ref = dir.replace(/\/$/, '');
			const entry = JSON.parse(readFileSync(`${root}${dir}entry.json`, 'utf8'));
			const files = {};
			for (const n of names) if (n !== 'entry.json' && statSync(`${root}${dir}${n}`).isFile()) files[n] = readFileSync(`${root}${dir}${n}`, 'utf8');
			out[ref] = { ref, ...entry, files, hash: bytesToHex(blake3(utf8ToBytes(canonical({ entry, files })))) };
			return;
		}
		for (const n of names) if (statSync(`${root}${dir}${n}`).isDirectory()) walk(`${dir}${n}/`);
	};
	for (const top of readdirSync(root).sort()) if (statSync(`${root}${top}`).isDirectory()) walk(`${top}/`);
	return out;
}

export const indexText = (all) => `// GENERATED by scripts/code-index.mjs from the files beside it. Do not edit: change the files, then run
// \`node scripts/code-index.mjs\`. Each entry: its ref (its path here), its entry.json, its files, and their BLAKE3 hash.
export const ENTRIES = ${JSON.stringify(all, null, '\t')};
`;

if (import.meta.url === `file://${process.argv[1]}`) {
	const text = indexText(entries());
	if (process.argv.includes('--check')) {
		const now = readFileSync(`${ROOT}index.js`, 'utf8');
		if (now !== text) {
			console.error('code/index.js is behind code/: run node scripts/code-index.mjs');
			process.exit(1);
		}
		console.log('code/index.js is current');
	} else {
		writeFileSync(`${ROOT}index.js`, text);
		console.log(`code/index.js: ${Object.keys(entries()).length} entries`);
	}
}
